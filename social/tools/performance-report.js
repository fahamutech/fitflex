#!/usr/bin/env node
// Monday performance analysis from the JSONL store. Reads publishes.jsonl,
// performance.jsonl and ideas.jsonl, takes the LATEST snapshot per publish, and
// compares by pillar, audience, format, language, platform and CTA keyword — but
// only where the sample supports it (MIN_N per group, default 3; two groups needed).
// Missing metrics stay null and are excluded from averages, never counted as 0.
//
//   node social/tools/performance-report.js [--min-n 3] [--write]
// --write rewrites the "Performance analysis" section of social/data/learnings.md
// between its markers (the rest of the file is kept).
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const dataDir = process.env.SOCIAL_DATA_DIR ? path.resolve(process.env.SOCIAL_DATA_DIR) : path.join(root, 'social', 'data');
const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const MIN_N = Number(opt('--min-n', 3));
const readJsonl = f => fs.existsSync(f) ? fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l)) : [];
const ideas = Object.fromEntries(readJsonl(path.join(dataDir, 'ideas.jsonl')).map(r => [r.id, r]));
const pubRows = readJsonl(path.join(dataDir, 'publishes.jsonl'));
const latestPub = {}; for (const p of pubRows) latestPub[p.id] = { ...(latestPub[p.id] || {}), ...p };
const published = Object.values(latestPub).filter(p => p.status === 'published');
const snaps = readJsonl(path.join(dataDir, 'performance.jsonl'));
const latestSnap = {}; for (const s of snaps) if (!latestSnap[s.publish_id] || s.observed_at > latestSnap[s.publish_id].observed_at) latestSnap[s.publish_id] = s;
const METRICS = ['reach', 'views', 'likes', 'comments', 'saves', 'shares', 'follows', 'interactions'];

const rows = published.map(p => {
  const idea = ideas[p.idea_id] || {}; const s = latestSnap[p.id] || null;
  const pubSpec = (() => { try { return JSON.parse(fs.readFileSync(path.join(root, 'social', 'content', p.idea_id, 'publish.json'), 'utf8')); } catch (e) { return {}; } })();
  return { publish_id: p.id, idea_id: p.idea_id, platform: p.platform, pillar: idea.pillar || null, audience: idea.audience || null, format: idea.format || null, language: idea.language_lead || null, cta: pubSpec.keyword || null, observed_at: s ? s.observed_at : null, metrics: Object.fromEntries(METRICS.map(m => [m, s && typeof s[m] === 'number' ? s[m] : null])) };
});
const withData = rows.filter(r => r.observed_at);

function compare(dim) {
  const groups = {}; withData.forEach(r => { const k = r[dim] == null ? 'unknown' : r[dim]; (groups[k] = groups[k] || []).push(r); });
  const keys = Object.keys(groups);
  const out = { dimension: dim, groups: {}, comparable: false, note: '' };
  for (const k of keys) {
    const g = groups[k]; const stats = {};
    for (const m of METRICS) { const vals = g.map(r => r.metrics[m]).filter(v => typeof v === 'number'); stats[m] = vals.length ? { n: vals.length, mean: +(vals.reduce((a, b) => a + b, 0) / vals.length).toFixed(1), min: Math.min(...vals), max: Math.max(...vals) } : null; }
    out.groups[k] = { n: g.length, stats };
  }
  const big = keys.filter(k => groups[k].length >= MIN_N);
  if (keys.length < 2) out.note = `only one ${dim} group so far; nothing to compare`;
  else if (big.length < 2) out.note = `fewer than two ${dim} groups reach n=${MIN_N} (${keys.map(k => `${k}: ${groups[k].length}`).join(', ')}); no comparison drawn`;
  else { out.comparable = true; out.note = `groups with n>=${MIN_N}: ${big.join(', ')}; differences are descriptive only (no significance test, posts differ in time, creative and audience)`; }
  return out;
}
const comparisons = ['pillar', 'audience', 'format', 'language', 'platform', 'cta'].map(compare);

const lines = [];
lines.push(`<!-- PERF:BEGIN generated by social/tools/performance-report.js on ${new Date().toISOString().slice(0, 10)} -->`);
lines.push('## Performance analysis');
lines.push('');
lines.push(`Published posts: ${published.length}. With at least one snapshot: ${withData.length}. Minimum per group to compare: ${MIN_N}. Latest snapshot per post is used; missing metrics are null and excluded from means.`);
lines.push('');
if (!published.length) lines.push('**No published posts yet.** Nothing to analyse; the pipeline is in place and this section regenerates on each Monday pull.');
else {
  lines.push('| Post | Platform | Pillar | Audience | Format | Lang | CTA | Observed | Reach | Views | Likes | Comments | Saves | Shares | Follows |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) { const m = r.metrics; const v = x => x == null ? 'null' : x; lines.push(`| ${r.idea_id} (${r.publish_id}) | ${r.platform} | ${r.pillar} | ${r.audience} | ${r.format} | ${r.language} | ${r.cta || ''} | ${r.observed_at || 'no snapshot'} | ${v(m.reach)} | ${v(m.views)} | ${v(m.likes)} | ${v(m.comments)} | ${v(m.saves)} | ${v(m.shares)} | ${v(m.follows)} |`); }
  lines.push('');
  lines.push('### Comparisons');
  lines.push('');
  for (const c of comparisons) {
    lines.push(`- **${c.dimension}**: ${c.note}.` + (c.comparable ? ' ' + Object.entries(c.groups).filter(([, g]) => g.n >= MIN_N).map(([k, g]) => `${k} (n=${g.n}): saves mean ${g.stats.saves ? g.stats.saves.mean : 'null'}, reach mean ${g.stats.reach ? g.stats.reach.mean : 'null'}`).join('; ') : ''));
  }
}
lines.push('');
lines.push('### Limitations');
lines.push('');
lines.push(`- Sample sizes above; no winner is declared below n=${MIN_N} per group or without two groups.`);
lines.push('- Attribution: metrics come from Metricool\'s Instagram/Facebook analytics for organic posts; DM keyword hits are not tracked until comment-to-DM exists; follows are per-post as reported by the network.');
lines.push('- Posts differ in publish time, creative, caption language and day; differences are descriptive, not causal.');
lines.push('- Instagram "impressions" and "video views" fields are deprecated at Metricool and are not collected.');
lines.push('');
lines.push('### Recommended next tests');
lines.push('');
if (!published.length) lines.push('- Publish the approved pilot, then the three brand-checked week-1 carousels, one per slot, so that each pillar has at least one post before any comparison is attempted.');
else lines.push('- Fill the smallest groups first (see the comparison notes) before changing the mix; keep one variable per test (format or language), not both.');
lines.push('<!-- PERF:END -->');
const text = lines.join('\n');

if (argv.includes('--write')) {
  const f = path.join(dataDir, 'learnings.md');
  const cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '# Learnings\n';
  const re = /<!-- PERF:BEGIN[\s\S]*?<!-- PERF:END -->/;
  fs.writeFileSync(f, re.test(cur) ? cur.replace(re, text) : cur.trimEnd() + '\n\n' + text + '\n');
  console.log(`learnings.md updated (${published.length} published, ${withData.length} with snapshots)`);
} else console.log(text);
