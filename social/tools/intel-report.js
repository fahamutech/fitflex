#!/usr/bin/env node
// Builds the factual half of the weekly intelligence report from the records:
// which accounts were observed, what was captured, grouped by category, with every
// line citing its dated source record. The interpretation half (why a pattern may
// work, proposed experiments) is written by the social-intel skill into the same
// file under the headings this script leaves in place, and is marked as interpretation.
//
//   node social/tools/intel-report.js --week 2026-W42 [--since 2026-10-10] [--until 2026-10-17]
// Writes social/intel/weekly/<week>.md. If the file exists, only the section between
// the FACTS markers is regenerated; the interpretation sections are kept.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const dataDir = process.env.SOCIAL_DATA_DIR ? path.resolve(process.env.SOCIAL_DATA_DIR) : path.join(root, 'social', 'data');
const outDir = process.env.SOCIAL_INTEL_DIR ? path.resolve(process.env.SOCIAL_INTEL_DIR) : path.join(root, 'social', 'intel', 'weekly');
const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const week = opt('--week'); if (!week) { console.error('--week YYYY-Www required'); process.exit(2); }
const since = opt('--since', '0000-00-00'), until = opt('--until', '9999-12-31');
const readJsonl = f => fs.existsSync(f) ? fs.readFileSync(f, 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l)) : [];
const wl = Object.fromEntries(readJsonl(path.join(dataDir, 'watchlist.jsonl')).map(w => [w.id, w]));
const ins = readJsonl(path.join(dataDir, 'inspiration.jsonl')).filter(r => (r.last_observed || r.captured_at) >= since && (r.last_observed || r.captured_at) <= until);
const byCat = {};
for (const r of ins) { const c = (wl[r.watchlist_id] || {}).category || 'unknown'; (byCat[c] = byCat[c] || []).push(r); }
const cats = Object.keys(byCat).sort();
const count = (rows, k) => { const m = {}; rows.forEach(r => { m[r[k]] = (m[r[k]] || 0) + 1; }); return Object.entries(m).sort((a, b) => b[1] - a[1]).map(([k2, v]) => `${k2} ${v}`).join(', '); };
const withMetrics = ins.filter(r => r.engagement && Object.values(r.engagement).some(v => typeof v === 'number'));

let facts = [];
facts.push(`<!-- FACTS:BEGIN generated by social/tools/intel-report.js on ${new Date().toISOString().slice(0, 10)}; do not edit by hand -->`);
facts.push(`## Observed facts (${since === '0000-00-00' ? 'all records' : `${since} to ${until}`})`);
facts.push('');
facts.push(`${ins.length} observations from ${new Set(ins.map(r => r.watchlist_id)).size} accounts; ${withMetrics.length} carry engagement numbers (the rest are null: not captured, never zero). Formats: ${count(ins, 'format') || 'none'}. Hook types: ${count(ins, 'hook_type') || 'none'}.`);
facts.push('');
for (const c of cats) {
  facts.push(`### ${c} (${byCat[c].length})`);
  facts.push('');
  facts.push('| Record | Account | Observed | Format | Hook | Pattern (our words) | Engagement | Source |');
  facts.push('|---|---|---|---|---|---|---|---|');
  for (const r of byCat[c]) {
    const w = wl[r.watchlist_id] || {}; const e = r.engagement; const es = e ? ['likes', 'comments', 'saves', 'shares', 'views'].filter(k => typeof e[k] === 'number').map(k => `${k} ${e[k]}`).join(', ') || 'null' : 'null';
    facts.push(`| ${r.id} | @${w.handle || '?'}${r.post_url ? ` ([post](${r.post_url}))` : ''} | ${r.last_observed || r.captured_at} | ${r.format} | ${r.hook_type} | ${r.pattern.replace(/\|/g, '/')} | ${es} | ${r.source || (w.source || '')} |`);
  }
  facts.push('');
}
facts.push('<!-- FACTS:END -->');
const factsText = facts.join('\n');

fs.mkdirSync(outDir, { recursive: true });
const file = path.join(outDir, `${week}.md`);
if (fs.existsSync(file)) {
  const cur = fs.readFileSync(file, 'utf8');
  const re = /<!-- FACTS:BEGIN[\s\S]*?<!-- FACTS:END -->/;
  if (!re.test(cur)) { console.error(`${file} has no FACTS markers; not touching it`); process.exit(1); }
  fs.writeFileSync(file, cur.replace(re, factsText));
  console.log(`facts regenerated in ${path.relative(root, file)} (${ins.length} observations)`);
} else {
  const skeleton = `# Weekly intelligence ${week}

Facts below come from \`social/data/inspiration.jsonl\` and \`watchlist.jsonl\`; every row names its record id, observation date and source. Everything under "Interpretation" is the analyst's reading and is labelled as such; nothing in it is a measured result.

${factsText}

## Interpretation (analyst reading, not measured)

_To be written by social-intel: which patterns recur, why they may work for FitFlex's audiences, with the record ids that support each reading._

## Hooks and formats worth testing for FitFlex

_To be written: each item = pattern, FitFlex adaptation in our own words, pillar/audience, evidence record ids, what would count as a signal._

## Proposed experiments (no guaranteed outcomes)

_To be written: 2 to 4 experiments with hypothesis, record(s) to create, metric to watch, minimum sample before judging._

## Limitations

_To be written: coverage, missing metrics, sampling bias, what was not observed._
`;
  fs.writeFileSync(file, skeleton);
  console.log(`report created ${path.relative(root, file)} (${ins.length} observations)`);
}
